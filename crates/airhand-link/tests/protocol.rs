//! 三种界面（桌面 / 网页控制台的 TypeScript、Android 的 Kotlin）和这里共用的协议样例：`tests/protocol.json`。
//!
//! * 媒体包：界面按 `airhand_proto::media` 的格式解析（`client/src/lib/media.ts`、`android/.../controller/Media.kt`）；
//! * 输入事件、界面命令：界面拼出来的 JSON 要和这里的一样（`airhand_link::controller::Command`）。
//!
//! 这个测试检查文件和 Rust 的实现一致；另外两边的测试（`npm test`、`./gradlew testDebugUnitTest`）读同一个文件。
//! 改了格式之后用 `AIRHAND_UPDATE_FIXTURES=1 cargo test -p airhand-link --test protocol` 重新生成，再让另外两边跟上。

use airhand_link::controller::Command;
use airhand_proto::media::{self, AudioHeader, VideoHeader};
use airhand_proto::session::{
    Codec, CursorShape, CursorSlot, CursorState, InputEvent, MouseButton, QualitySettings,
    SystemAction, TouchPhase,
};
use serde_json::{Value, json};

fn hex(b: &[u8]) -> String {
    b.iter().map(|b| format!("{b:02x}")).collect()
}

/// 交给界面的包（线上的包去掉长度前缀）
fn packet(header: &[u8; media::HEADER_LEN], payload: &[u8]) -> Vec<u8> {
    media::frame(header, &[payload])[4..].to_vec()
}

